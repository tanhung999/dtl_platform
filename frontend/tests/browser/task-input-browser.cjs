// Local Docker QA. Only this run's task is removed.
const { chromium } = require('../.browser-tools/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

async function main() {
  const base = process.env.CALENDAR_TEST_URL || 'http://localhost:5173';
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'en-US', timezoneId: 'America/New_York' });
  const page = await context.newPage();
  let token, id, timeOnlyId; const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const title = `[Input QA ${Date.now()}] Hạn kiểu Việt Nam`;
  const today = new Date(Date.now() + 7 * 3600000).toISOString().slice(0, 10);
  const overdueDay = new Date(Date.parse(today + 'T00:00:00Z') - 2 * 86400000).toISOString().slice(0, 10);
  const formatted = date => date.split('-').reverse().join('/');
  try {
    await page.goto(base);
    await page.getByLabel('Tên đăng nhập hoặc Email').fill(process.env.CALENDAR_TEST_USERNAME || 'admin');
    await page.getByLabel('Mật khẩu', { exact: true }).fill(process.env.CALENDAR_TEST_PASSWORD || 'admin123');
    await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click();
    await page.locator('.tasks-widget').waitFor();
    token = await page.evaluate(() => localStorage.getItem('dtl_platform_token'));
    const date = page.getByLabel('Ngày đến hạn', { exact: true });
    const initialTime = page.getByLabel('Giờ đến hạn', { exact: true });
    assert.equal(await initialTime.isDisabled(), false, 'Time can be selected before date');
    await initialTime.click();
    await page.getByLabel('Chọn giờ', { exact: true }).selectOption('14');
    await page.getByLabel('Chọn phút', { exact: true }).selectOption('05');
    await page.locator('.app-time-popover').getByRole('button', { name: 'Xong', exact: true }).click();
    assert.equal(await date.inputValue(), '', 'Selecting time does not force date selection');
    assert.equal(await page.locator('.task-quick-form .app-time-period').innerText(), 'PM');
    await page.getByLabel('Tên việc mới').fill(title + ' Chỉ giờ');
    const timeOnlyCreated = page.waitForResponse(r => r.url().endsWith('/api/tasks') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Tạo công việc', exact: true }).click();
    const timeResponse = await timeOnlyCreated, timeOnly = await timeResponse.json();
    timeOnlyId = timeOnly.id;
    assert.equal(timeResponse.status(), 201);
    assert.equal(timeResponse.request().postDataJSON().due_date, null);
    assert.equal(timeOnly.due_date, new Date(Date.parse(timeOnly.created_at) + 7 * 3600000).toISOString().slice(0, 10));
    assert.equal(timeOnly.due_time, '14:05');
    await page.locator(`[data-task-id="${timeOnlyId}"]`).waitFor();
    await page.locator(`.calendar-widget [data-deadline-id="${timeOnlyId}"]`).waitFor();
    assert.equal(await date.getAttribute('placeholder'), 'dd/mm/yyyy');
    await page.getByLabel('Tên việc mới').fill(title);
    await page.getByLabel('Ưu tiên việc mới').selectOption('URGENT');
    await date.fill('31/02/2026');
    await page.getByRole('button', { name: 'Tạo công việc', exact: true }).click();
    assert.equal(await date.evaluate(el => el.validity.valid), false);
    assert.equal(await page.getByRole('button', { name: title, exact: true }).count(), 0);
    await date.fill(formatted(overdueDay));
    const created = page.waitForResponse(r => r.url().endsWith('/api/tasks') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Tạo công việc', exact: true }).click();
    const result = await created; id = (await result.json()).id;
    assert.equal(result.request().postDataJSON().due_date, overdueDay);
    const row = page.locator(`[data-task-id="${id}"]`); await row.waitFor();
    assert.ok((await row.innerText()).includes('Quá hạn · trễ 2 ngày'));
    const borders = await row.evaluate(el => { const s = getComputedStyle(el); return [s.borderLeftColor, s.borderTopColor, s.borderRightColor, s.borderBottomColor]; });
    assert.equal(borders[0], 'rgb(220, 38, 38)');
    assert.ok(borders.slice(1).every(color => color === 'rgba(0, 0, 0, 0)'));
    await row.getByRole('button', { name: /^Sửa / }).click();
    const modalDate = page.getByLabel('Ngày đến hạn', { exact: true });
    assert.equal(await modalDate.inputValue(), formatted(overdueDay));
    assert.ok(await modalDate.isDisabled());
    await page.getByRole('dialog').getByRole('button', { name: 'Dời lịch', exact: true }).click();
    const moveDate = page.locator('.reschedule-dialog').getByLabel('Ngày đến hạn mới', { exact: true });
    await moveDate.fill('29/02/2026');
    await page.locator('.reschedule-dialog').getByRole('button', { name: 'Dời lịch', exact: true }).last().click();
    assert.equal(await page.locator('.reschedule-dialog').isVisible(), true, 'Invalid date blocks saving');
    await moveDate.click();
    await page.locator('.app-date-popover').waitFor();
    await page.locator('.app-date-popover').getByRole('button', { name: 'Hôm nay', exact: true }).click();
    assert.equal(await moveDate.inputValue(), formatted(today));
    assert.equal(await moveDate.evaluate(el => el.validity.valid), true);
    await page.locator('.reschedule-dialog').getByRole('button', { name: 'Dời lịch', exact: true }).last().click();
    await page.locator('.reschedule-dialog').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Lưu công việc', exact: true }).click();
    await page.getByRole('dialog').waitFor({ state: 'hidden' });
    await row.locator('.task-overdue-text').waitFor({ state: 'hidden' });
    const filter = page.locator('.task-filters button').filter({ hasText: /^Chưa làm/ });
    await filter.click(); assert.equal(await filter.getAttribute('aria-pressed'), 'true');
    assert.ok(await filter.evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 12));
    await page.getByRole('button', { name: 'Chọn ngày đến hạn', exact: true }).click();
    await page.getByRole('button', { name: 'Chọn ngày ' + formatted(today), exact: true }).click();
    assert.equal(await date.inputValue(), formatted(today));
    await date.click();
    await page.locator('.app-date-popover').waitFor();
    await page.locator('.tasks-widget .widget-title').click();
    assert.equal(await page.locator('.app-date-popover').count(), 0, 'Click outside date field closes its calendar');
    const time = page.getByLabel('Giờ đến hạn', { exact: true });
    assert.equal(await time.getAttribute('type'), 'text', '24-hour rendering is independent of US browser locale');
    assert.equal(await time.getAttribute('placeholder'), 'HH:mm');
    await time.fill('24:01');
    assert.equal(await time.evaluate(el => el.validity.valid), false);
    await time.fill('14:00');
    assert.equal(await time.inputValue(), '14:00');
    assert.equal(await time.evaluate(el => el.validity.valid), true);
    assert.equal(await page.locator('.task-quick-form .app-time-period').innerText(), 'PM');
    await time.fill('00:00');
    assert.equal(await page.locator('.task-quick-form .app-time-period').innerText(), 'AM');
    await time.fill('11:59');
    assert.equal(await page.locator('.task-quick-form .app-time-period').innerText(), 'AM');
    await time.fill('12:00');
    assert.equal(await page.locator('.task-quick-form .app-time-period').innerText(), 'PM');
    await time.click();
    await page.locator('.app-time-popover').waitFor();
    await page.getByLabel('Chọn giờ', { exact: true }).selectOption('14');
    await page.getByLabel('Chọn phút', { exact: true }).selectOption('25');
    assert.equal(await time.inputValue(), '14:25');
    await page.locator('.tasks-widget .widget-title').click();
    assert.equal(await page.locator('.app-time-popover').count(), 0, 'Click outside time field closes its picker');
    await time.click();
    await page.locator('.app-time-popover').getByRole('button', { name: 'Xóa giờ', exact: true }).click();
    assert.equal(await time.inputValue(), '');
    await page.getByRole('button', { name: 'Chọn ngày đến hạn', exact: true }).click();
    await page.locator('.app-date-popover').getByRole('button', { name: 'Xóa hạn', exact: true }).click();
    assert.equal(await date.inputValue(), '');
    assert.equal(await page.getByLabel('Giờ đến hạn', { exact: true }).isDisabled(), false);
    await page.getByRole('button', { name: 'Chọn ngày đến hạn', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.app-date-popover').count(), 0);
    fs.mkdirSync(path.join(__dirname, '../artifacts'), { recursive: true });
    await page.locator('.tasks-widget').screenshot({ path: path.join(__dirname, '../artifacts/task-input-desktop.png') });
    await page.getByRole('button', { name: 'Toggle dark/light theme' }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Chọn ngày đến hạn', exact: true }).click();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.locator('.tasks-widget').screenshot({ path: path.join(__dirname, '../artifacts/task-input-mobile-dark.png') });
    assert.deepEqual(errors, []);
    console.log('PASS: dd/mm/yyyy with US locale, invalid date blocked, ISO payload, whole-field date/time pickers, outside-click dismissal, hour/minute selection/clear/Escape, overdue duration/style, filters, realtime edit, mobile/dark.');
  } finally {
    if (token) for (const taskId of [id, timeOnlyId].filter(Boolean)) await context.request.delete(base + '/api/tasks/' + taskId, { headers: { Authorization: `Bearer ${token}` } });
    await browser.close();
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
