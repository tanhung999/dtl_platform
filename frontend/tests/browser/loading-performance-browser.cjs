const { chromium } = require('../.browser-tools/node_modules/playwright');
const { createTestUsers } = require('../support/test-users.cjs');
const assert = require('node:assert/strict');
const base = process.env.PLATFORM_BASE_URL || 'http://127.0.0.1:5173';
(async () => {
  const fixture = createTestUsers(1); let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1550, height: 950 } });
    page.setDefaultTimeout(25000);
    await page.route(/fonts\.(googleapis|gstatic)\.com/, route => route.abort());
    let listRequests = 0;
    const modules = [], errors = [];
    page.on('request', request => {
      const url = new URL(request.url());
      if (url.pathname === '/api/tasks/collection') listRequests++;
      if (url.pathname.endsWith('.js') || url.pathname.endsWith('.tsx')) modules.push(url.pathname);
    });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/platform', { waitUntil: 'domcontentloaded' });
    await page.waitForURL(url => url.pathname === '/login');
    assert.ok(!modules.some(url => /DashboardPage|CalendarWorkspace|ProfileTab|AdminPage/.test(url)), JSON.stringify(modules));
    await page.getByLabel('Tên đăng nhập hoặc Email').fill(fixture.accounts[0].username);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(fixture.accounts[0].password);
    await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click();
    await page.locator('.enterprise-apps.is-detailed').waitFor();
    assert.equal(await page.locator('.workspace-shell').evaluate(element => getComputedStyle(element).display), 'grid');
    const legacyIcon = await page.request.get(base + '/icon-platform.png');
    assert.equal(legacyIcon.status(), 200);
    assert.ok(legacyIcon.headers()['content-type'].includes('image/png'));
    assert.equal(listRequests, 0);
    assert.ok(!modules.some(url => /CalendarWorkspace|ProfileTab|AdminPage/.test(url)), JSON.stringify(modules));
    const nav = page.getByRole('navigation', { name: 'Điều hướng chính' });
    await nav.getByRole('link', { name: 'DT My Note', exact: true }).click();
    await page.locator('.notes-page').waitFor();
    assert.equal(listRequests, 0);
    const token = await page.evaluate(() => localStorage.getItem('dtl_platform_token'));
    const response = await page.request.post(base + '/api/tasks', { headers: { Authorization: 'Bearer ' + token }, data: { title: 'Audit deferred task' } });
    assert.ok(response.ok(), await response.text());
    const task = await response.json();
    await page.getByRole('searchbox', { name: 'Tìm kiếm toàn hệ thống' }).fill('Audit deferred task');
    await page.locator('.search-result').getByText('Audit deferred task', { exact: true }).click();
    const detail = page.getByRole('dialog', { name: 'Chi tiết công việc', exact: true });
    await detail.waitFor();
    await detail.getByLabel('Tên công việc', { exact: true }).fill('Audit deferred task updated');
    await detail.getByRole('button', { name: 'Lưu công việc', exact: true }).click();
    await detail.waitFor({ state: 'hidden' });
    assert.equal(listRequests, 0);
    const saved = await page.request.get(base + '/api/tasks/' + task.id, { headers: { Authorization: 'Bearer ' + token } });
    assert.equal((await saved.json()).title, 'Audit deferred task updated');

    const profileChunk = /\/src\/features\/profile\/ProfileTab\.tsx(?:\?|$)|\/assets\/ProfileTab-[^/]+\.js/;
    await page.route(profileChunk, route => route.abort());
    await nav.getByRole('link', { name: 'Hồ sơ', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Không thể mở trang.' }).waitFor();
    await page.unroute(profileChunk);
    await page.getByRole('button', { name: 'Thử tải lại', exact: true }).click();
    await page.locator('.profile-page').waitFor();
    assert.equal(listRequests, 0);
    await nav.getByRole('link', { name: 'Trang chủ', exact: true }).click();
    await page.locator('.workspace-home').waitFor();
    await page.waitForFunction(() => !!document.querySelector('.calendar-widget'));
    assert.ok(listRequests > 0);
    await nav.getByRole('link', { name: 'DT Task', exact: true }).click();
    await page.getByRole('heading', { name: 'DT Task', exact: true }).waitFor();
    await page.locator(`[data-task-id="${task.id}"]`).waitFor();
    assert.deepEqual(errors.filter(message => !(message.includes('Failed to fetch dynamically imported module') && message.includes('ProfileTab'))), []);
    console.log('PASS login skips workspace code, unrelated pages skip calendar/profile/admin code and task collection, task details save from search without a loaded list, visible lists load on demand');
  } finally { await browser?.close();fixture.cleanup(); }
})().catch(error => { console.error(error);process.exitCode = 1; });
