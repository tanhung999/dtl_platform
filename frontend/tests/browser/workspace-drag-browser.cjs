const { chromium } = require('../.browser-tools/node_modules/playwright');
const { createDragUsers } = require('../support/test-users.cjs');
const assert = require('node:assert/strict');
async function main() {
  const fixture = createDragUsers();
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const first = await browser.newContext({ viewport: { width: 1440, height: 1600 } }), second = await browser.newContext({ viewport: { width: 1440, height: 1600 } });
  const a = await first.newPage(), b = await second.newPage(), errors = [];
  const base = 'http://127.0.0.1:5173';
  let token, launches = 0;
  const noteVersions = new Map();
  for (const page of [a, b]) page.on('pageerror', error => errors.push(error.message));
  a.on('request', request => { if (request.url().includes('/api/sso/launch')) launches++; });
  const api = async (method, route, data) => { if (method === 'PATCH' && route.startsWith('notes/')) { const notes = await api('GET', 'notes'); const current = notes.find(note => note.id === route.split('/')[1]); data = { ...data, expected_version: current?.version ?? noteVersions.get(route.split('/')[1]) ?? data.expected_version }; } const response = await first.request.fetch(base + '/api/' + route, { method, data, headers: { Authorization: `Bearer ${token}` } }); assert.ok(response.ok(), `${route}: ${response.status()} ${await response.text()}`); const value = response.status() === 204 ? null : await response.json(); if (route.startsWith('notes/') && value?.version !== undefined) noteVersions.set(value.id, value.version); return value; };
  const login = async (page, account) => { await page.goto(base); await page.getByLabel('Tên đăng nhập hoặc Email').fill(account.username); await page.getByLabel('Mật khẩu', { exact: true }).fill(account.password); await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click(); await page.locator('.calendar-widget').waitFor(); await page.locator('[data-sort-group="apps"] .workspace-sort-handle:not(:disabled)').first().waitFor(); };
  const ids = (page, kind) => page.locator(`[data-sort-group="${kind}"] [data-sort-id]`).evaluateAll(nodes => nodes.map(node => node.dataset.sortId));
  const drag = async (source, target) => { await source.scrollIntoViewIfNeeded(); const s = await source.boundingBox(), t = await target.boundingBox(); await a.mouse.move(s.x + s.width / 2, s.y + s.height / 2); await a.mouse.down(); await a.mouse.move(s.x + s.width / 2 + 12, s.y + s.height / 2, { steps: 3 }); await a.locator('.workspace-sort-preview').waitFor(); await a.mouse.move(t.x + t.width / 2, t.y + t.height / 2, { steps: 20 }); await a.mouse.up(); };
  try {
    await login(a, fixture.accounts[0]); await login(b, fixture.accounts[0]); token = await a.evaluate(() => localStorage.getItem('dtl_platform_token'));
    const appIds = await ids(a, 'apps');
    await drag(a.locator(`[data-sort-id="${appIds[2]}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${appIds[0]}"]`));
    await b.waitForFunction(id => document.querySelector('[data-sort-group="apps"] [data-sort-id]')?.dataset.sortId === id, appIds[2]);
    await a.locator('.task-calendar-toast').getByRole('button', { name: '\u0048\u006f\u00e0\u006e \u0074\u00e1\u0063', exact: true }).click();
    await b.waitForFunction(id => document.querySelector('[data-sort-group="apps"] [data-sort-id]')?.dataset.sortId === id, appIds[0]);
    await drag(a.locator(`[data-sort-id="${appIds[2]}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${appIds[0]}"]`));
    await b.waitForFunction(id => document.querySelector('[data-sort-group="apps"] [data-sort-id]')?.dataset.sortId === id, appIds[2]);
    assert.equal(launches, 0, 'Dragging an app does not launch SSO');
    await a.reload(); await a.locator('.calendar-widget').waitFor();
    await a.locator('[data-sort-group="apps"] .workspace-sort-handle:not(:disabled)').first().waitFor();
    assert.equal((await ids(a, 'apps'))[0], appIds[2]);
    const bookmarks = [];
    for (const title of ['QA Bookmark A', 'QA Bookmark B']) bookmarks.push(await api('POST', 'bookmarks', { title, url: 'https://example.com' }));
    await a.locator(`[data-sort-id="${bookmarks[1].id}"]`).waitFor();
    const before = await ids(a, 'bookmarks');
    await drag(a.locator(`[data-sort-id="${bookmarks[1].id}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${before[0]}"]`));
    await b.waitForFunction(id => document.querySelector('[data-sort-group="bookmarks"] [data-sort-id]')?.dataset.sortId === id, bookmarks[1].id);
    const notes = [];
    for (const title of ['QA Note A', 'QA Note B', 'QA Note C']) notes.push(await api('POST', 'notes', { title, content: 'Drag fixture', color: '#bbf7d0', is_pinned: false }));
    await a.locator(`[data-sort-id="${notes[2].id}"]`).waitFor();
    await drag(a.locator(`[data-sort-id="${notes[2].id}"] .workspace-sort-handle`), a.locator('.notes-pin-zone'));
    await b.locator(`[data-sort-id="${notes[2].id}"].pinned`).waitFor();
    assert.equal((await ids(b, 'notes'))[0], notes[2].id);
    assert.equal(await a.locator('.task-calendar-toast').count(), 0, 'Note dragging has no toast');
    // Cross-section drops put an unpinned note first after the pinned group.
    const unpinned = await a.locator('[data-sort-section="notes-unpinned"] [data-sort-id]').evaluateAll(nodes => nodes.map(node => node.dataset.sortId));
    const resetId = unpinned[unpinned.length - 1];
    await drag(a.locator(`[data-sort-id="${resetId}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${notes[2].id}"]`));
    await b.waitForFunction(id => document.querySelector('[data-sort-section="notes-unpinned"] [data-sort-id]')?.dataset.sortId === id, resetId);
    assert.equal((await ids(a, 'notes'))[0], notes[2].id);
    assert.equal((await api('GET', 'notes')).find(note => note.id === resetId).is_pinned, false);
    // A lone pinned note is already last, so a cross-section drop is a no-op.
    const beforeCross = await ids(a, 'notes'), versionBefore = (await api('GET', 'workspace/layout')).notes.version;
    await drag(a.locator(`[data-sort-id="${notes[2].id}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${resetId}"]`));
    assert.deepEqual(await ids(a, 'notes'), beforeCross);
    assert.equal((await api('GET', 'workspace/layout')).notes.version, versionBefore);
    // Outside the Notes widget is a cancellation, not a reorder.
    await drag(a.locator(`[data-sort-id="${resetId}"] .workspace-sort-handle`), a.locator('[data-sort-group="apps"]'));
    assert.deepEqual(await ids(a, 'notes'), beforeCross);
    await a.getByRole('button', { name: `Bỏ ghim ${notes[2].title}`, exact: true }).click();
    await b.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`)?.classList.contains('pinned'), notes[2].id);
    await a.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`)?.classList.contains('pinned'), notes[2].id);
    assert.equal((await api('GET', 'notes')).find(note => note.id === notes[2].id).is_pinned, false);
    await drag(a.locator(`[data-sort-id="${notes[2].id}"] .workspace-sort-handle`), a.locator('.notes-pin-zone'));
    await b.locator(`[data-sort-id="${notes[2].id}"].pinned`).waitFor();
    await a.locator(`[data-sort-id="${notes[2].id}"].pinned`).waitFor();
    await a.getByRole('button', { name: `Bỏ ghim ${notes[2].title}`, exact: true }).click();
    await b.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`)?.classList.contains('pinned'), notes[2].id);
    await a.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`)?.classList.contains('pinned'), notes[2].id);
    const beforeNotes = await ids(a, 'notes');
    const last = beforeNotes[beforeNotes.length - 1];
    await drag(a.locator(`[data-sort-id="${last}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${beforeNotes[0]}"]`));
    await b.waitForFunction(id => document.querySelector('[data-sort-group="notes"] [data-sort-id]')?.dataset.sortId === id, last);
    await a.reload(); await a.locator('[data-sort-group="notes"] [data-sort-id]').first().waitFor();
    await a.locator('[data-sort-group="notes"] .workspace-sort-handle:not(:disabled)').first().waitFor();
    assert.equal((await ids(a, 'notes'))[0], last);
    // Two pinned notes: reorder before a delayed save finishes, and roll back failed saves.
    for (const note of notes.slice(0, 2)) await api('PATCH', `notes/${note.id}`, { is_pinned: true });
    for (const note of notes.slice(0, 2)) await a.locator(`[data-sort-id="${note.id}"].pinned`).waitFor();
    await a.locator('[data-sort-group="notes"] .workspace-sort-handle:not(:disabled)').first().waitFor();
    const pinnedBefore = await ids(a, 'notes');
    const persistedBefore = (await api('GET', 'workspace/layout')).notes.ids;
    let releaseSave;
    const gate = new Promise(resolve => { releaseSave = resolve; });
    const delayedSave = async route => { if (route.request().method() !== 'POST') return route.continue(); await gate; await route.continue(); };
    await a.route('**/api/notes/*/move', delayedSave);
    await drag(a.locator(`[data-sort-id="${pinnedBefore[1]}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${pinnedBefore[0]}"]`));
    await a.waitForFunction(id => document.querySelector('[data-sort-group="notes"] [data-sort-id]')?.dataset.sortId === id, pinnedBefore[1]);
    assert.deepEqual((await api('GET', 'workspace/layout')).notes.ids, persistedBefore, 'UI moves before server persists');
    releaseSave();
    await a.locator('[data-sort-group="notes"] .workspace-sort-handle:not(:disabled)').first().waitFor();
    await a.unroute('**/api/notes/*/move', delayedSave);
    await b.waitForFunction(id => document.querySelector('[data-sort-group="notes"] [data-sort-id]')?.dataset.sortId === id, pinnedBefore[1]);
    // With two pinned notes, a cross-section drop moves the first to the pinned tail.
    const pinnedFirst = (await ids(a, 'notes'))[0];
    const unpinnedTarget = a.locator('[data-sort-section="notes-unpinned"] [data-sort-id]').first();
    await drag(a.locator(`[data-sort-id="${pinnedFirst}"] .workspace-sort-handle`), unpinnedTarget);
    for (const page of [a, b]) await page.waitForFunction(id => [...document.querySelectorAll('[data-sort-section="notes-pinned"] [data-sort-id]')].at(-1)?.dataset.sortId === id, pinnedFirst);
    assert.equal((await api('GET', 'notes')).find(note => note.id === pinnedFirst).is_pinned, true);
    assert.equal(await a.locator('.task-calendar-toast').count(), 0);
    const afterSave = await ids(a, 'notes');
    const failedSave = async route => route.request().method() === 'POST' ? route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ detail: 'QA save failure' }) }) : route.continue();
    await a.route('**/api/notes/*/move', failedSave);
    const failureResponse = a.waitForResponse(response => response.url().endsWith('/move') && response.request().method() === 'POST');
    await drag(a.locator(`[data-sort-id="${afterSave[1]}"] .workspace-sort-handle`), a.locator(`[data-sort-id="${afterSave[0]}"]`));
    await a.locator('[data-sort-group="notes"] .workspace-sort-handle:not(:disabled)').first().waitFor();
    assert.equal((await failureResponse).status(), 500);
    await a.waitForFunction(expected => JSON.stringify([...document.querySelectorAll('[data-sort-group="notes"] [data-sort-id]')].map(node => node.dataset.sortId)) === JSON.stringify(expected), afterSave);
    assert.equal(await a.locator('.task-calendar-toast').count(), 0);
    assert.deepEqual(await ids(a, 'notes'), afterSave, 'Failed save restores previous order');
    await a.unroute('**/api/notes/*/move', failedSave);
    // Archive/delete clean saved IDs and propagate to the other tab.
    const removedId = notes[2].id;
    const beforeArchive = (await api('GET', 'workspace/layout')).notes;
    assert.ok(beforeArchive.ids.includes(removedId));
    await api('PATCH', `notes/${removedId}`, { is_archived: true });
    for (const page of [a, b]) await page.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`), removedId);
    const afterArchive = (await api('GET', 'workspace/layout')).notes;
    assert.ok(!afterArchive.ids.includes(removedId));
    assert.ok(afterArchive.version > beforeArchive.version);
    await api('PATCH', `notes/${removedId}`, { is_archived: false, expected_version: (notes.find(note => note.id === removedId)?.version ?? 0) + 1 });
    await b.locator(`[data-sort-id="${removedId}"]`).waitFor();
    assert.equal((await api('GET', 'workspace/layout')).notes.ids.at(-1), removedId, 'Restore appends rather than resurrecting an old slot');
    const restoredOrder = await ids(a, 'notes');
    const layoutBeforeRestoreOrder = (await api('GET', 'workspace/layout')).notes;
    await api('PUT', 'workspace/layout/notes', { ids: restoredOrder, expected_version: layoutBeforeRestoreOrder.version });
    await api('DELETE', `notes/${removedId}`);
    await b.waitForFunction(id => !document.querySelector(`[data-sort-id="${id}"]`), removedId);
    assert.ok(!(await api('GET', 'workspace/layout')).notes.ids.includes(removedId));
    // Moving the note body never activates dragging.
    const bodyBox = await a.locator(`[data-sort-id="${afterSave[0]}"] .note-title`).boundingBox();
    await a.mouse.move(bodyBox.x + 5, bodyBox.y + 5); await a.mouse.down();
    await a.mouse.move(bodyBox.x + 50, bodyBox.y + 5, { steps: 5 });
    assert.equal(await a.locator('.workspace-sort-preview').count(), 0);
    await a.mouse.up();
    if (await a.getByRole('dialog').count()) await a.keyboard.press('Escape');
    const other = await browser.newContext(); const c = await other.newPage(); await login(c, fixture.accounts[1]);
    assert.deepEqual(await ids(c, 'apps'), appIds);
    assert.equal(await c.locator('[data-sort-group="bookmarks"] [data-sort-id]').count(), before.length - bookmarks.length);
    await other.close();
    await a.setViewportSize({ width: 390, height: 844 });
    assert.ok(await a.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    assert.deepEqual(errors, []);
    console.log('PASS: archive/delete order cleanup and realtime restore, isolated note drop sections, unpinned reset, pinned cross-drop moves to group tail, no note toasts, optimistic pinned-note swap with delayed API, save rollback, handle-only activation, app/bookmark/note dragging, note drag-to-pin/unpin, two-session realtime, reload persistence, user isolation, no accidental SSO launch and mobile.');
  } finally { await browser.close(); fixture.cleanup(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
