const { chromium } = require('../.browser-tools/node_modules/playwright');
const { createDragUsers } = require('../support/test-users.cjs');
const assert = require('node:assert/strict');
async function main() {
  const fixture = createDragUsers(1), browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1600, height: 1200 } }), page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = 'http://127.0.0.1:5173'; let token;
  const api = async (method, path, data) => { const response = await context.request.fetch(base + '/api/' + path, { method, data, headers: { Authorization: `Bearer ${token}` } }); assert.ok(response.ok(), `${path}: ${response.status()}`); return response.status() === 204 ? null : response.json(); };
  try {
    await page.goto(base); await page.getByLabel('Tên đăng nhập hoặc Email').fill(fixture.accounts[0].username); await page.getByLabel('Mật khẩu', { exact: true }).fill(fixture.accounts[0].password); await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click(); await page.locator('.calendar-widget').waitFor();
    token = await page.evaluate(() => localStorage.getItem('dtl_platform_token'));
    const date = await page.locator('.calendar-widget-week button').nth(3).getAttribute('data-date');
    const events = [];
    for (const title of ['aaa resize QA', 'ccc peer QA']) events.push(await api('POST', 'calendar/events', { title, starts_at: date + 'T09:00:00+07:00', ends_at: date + 'T10:00:00+07:00', is_all_day: false }));
    await page.getByRole('button', { name: 'Mở lịch đầy đủ' }).click();
    const button = id => page.locator(`button[data-event-id="${id}"]`), frame = id => button(id).locator('..');
    await button(events[1].id).waitFor();
    const first = frame(events[0].id), peer = frame(events[1].id);
    await first.scrollIntoViewIfNeeded();
    const before = await first.boundingBox(), otherBefore = await peer.boundingBox();
    assert.ok(before.width < (await first.locator('..').boundingBox()).width * .6, 'Fixture uses two overlapping lanes');
    await page.mouse.move(5, 5);
    assert.equal(await peer.locator('[data-event-resize="end"]').evaluate(node => getComputedStyle(node).opacity), '0');
    const handle = first.locator('[data-event-resize="end"]'); await handle.hover();
    assert.equal(await handle.evaluate(node => getComputedStyle(node).opacity), '1');
    assert.equal(await first.locator('[data-event-resize="start"] span').evaluate(node => getComputedStyle(node).opacity), '0');
    const startResize = async () => {
      await handle.hover(); const s = await handle.boundingBox();
      await page.mouse.move(s.x + s.width / 2, s.y + s.height / 2); await page.mouse.down();
      await page.mouse.move(s.x + s.width / 2 + 12, s.y + s.height / 2, { steps: 3 });
      await page.locator('.calendar-resize-ghost').waitFor();
      const slot = page.locator(`.calendar-time-slot[data-drop-date="${date}"][data-drop-time="10:00"]`);
      await slot.scrollIntoViewIfNeeded(); const t = await slot.boundingBox();
      await page.mouse.move(t.x + t.width / 4, t.y + t.height / 2, { steps: 20 });
      await page.waitForFunction(() => document.querySelector('.calendar-resize-time')?.textContent === '09:00 – 10:30');
    };
    await startResize();
    const ghost = page.locator('.calendar-resize-ghost');
    assert.equal(await ghost.count(), 1);
    const box = await ghost.boundingBox(), peerNow = await peer.boundingBox();
    assert.ok(Math.abs(box.x - before.x) < 2 && Math.abs(box.width - before.width) < 2, 'Ghost keeps the original lane');
    assert.ok(Math.abs(box.height - 90) < 2, 'Ghost ends on the 10:30 fifteen-minute step');
    assert.deepEqual(peerNow, otherBefore, 'Peer geometry never changes while resizing');
    assert.ok(box.x + box.width <= peerNow.x + 1 || peerNow.x + peerNow.width <= box.x + 1, 'Ghost does not cover the peer lane');
    assert.equal(await first.evaluate(node => getComputedStyle(node).visibility), 'hidden');
    assert.equal(await peer.evaluate(node => getComputedStyle(node).opacity), '0.6');
    assert.equal(await page.locator('.calendar-event-drag-preview, .calendar-deadline-drop-caption, .drag-settle-copy').count(), 0);
    assert.equal(await page.locator('.calendar-resize-time').count(), 1);
    assert.ok(await page.locator('.calendar-resize-time').evaluate(node => node.scrollWidth <= node.clientWidth), 'Time label does not clip horizontally in a half-width lane');
    assert.equal(await button(events[0].id).getAttribute('title'), null);
    assert.equal(await button(events[1].id).getAttribute('title'), null);
    const line = await page.locator('[data-resize-boundary="end"]').boundingBox();
    assert.ok(Math.abs(line.y - box.y - box.height) < 2);
    require('node:fs').mkdirSync('tests/artifacts', { recursive: true });
    await page.screenshot({ path: 'tests/artifacts/calendar-resize-overlap.png', fullPage: true });
    await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
    assert.equal(await ghost.evaluate(node => getComputedStyle(node).backgroundColor), 'rgb(30, 58, 95)');
    await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
    await page.keyboard.press('Escape'); await page.mouse.up();
    assert.equal(await ghost.count(), 0);
    assert.equal(await first.evaluate(node => getComputedStyle(node).visibility), 'visible');
    assert.equal(await peer.evaluate(node => getComputedStyle(node).opacity), '1');
    assert.ok(await button(events[0].id).getAttribute('title'));
    await startResize(); await page.mouse.up();
    await page.locator('.calendar-event-toast').getByRole('button', { name: 'Hoàn tác', exact: true }).waitFor();
    const saved = (await api('GET', `calendar/events?start=${encodeURIComponent(date+'T00:00:00+07:00')}&end=${encodeURIComponent(date+'T23:59:59+07:00')}`)).find(event => event.id === events[0].id);
    assert.equal(Date.parse(saved.ends_at), Date.parse(date+'T10:30:00+07:00'));
    assert.equal(await ghost.count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: single resize ghost, original lane width, stationary peer, source hidden, single time label, no floating overlay/caption/tooltips, hover-only grip, 15-minute boundary, dark mode, cancel restore and saved end time.');
  } finally { await browser.close(); fixture.cleanup(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
