const { chromium } = require('../.browser-tools/node_modules/playwright');
const { createTestUsers } = require('../support/test-users.cjs');
const assert = require('node:assert/strict');
(async () => {
  const fixture = createTestUsers(1); let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, locale: 'en-US', timezoneId: 'America/New_York' });
    page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5173');
    await page.getByLabel('Tên đăng nhập hoặc Email').fill(fixture.accounts[0].username);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(fixture.accounts[0].password);
    await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click();
    const calendar = page.locator('.calendar-widget'); await calendar.waitFor();
    const api = (path, method = 'GET', body) => page.evaluate(async ({path,method,body}) => {
      const response = await fetch('/api/' + path, { method, headers: { Authorization: 'Bearer ' + localStorage.getItem('dtl_platform_token'), 'Content-Type': 'application/json' }, ...(body ? {body: JSON.stringify(body)} : {}) });
      if (!response.ok) throw new Error(await response.text());
      return response.status === 204 ? null : response.json();
    }, { path, method, body });
    const today = await page.evaluate(() => new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' }));
    const display = day => day.split('-').reverse().join('/');
    const noteEditor = page.getByRole('dialog', { name: 'Ghi chú', exact: true });
    await calendar.getByRole('button', { name: 'Tạo sự kiện', exact: true }).click();
    const eventEditor = page.getByRole('dialog', { name: 'Tạo sự kiện mới', exact: true });
    assert.equal(await eventEditor.getByRole('button', { name: 'Chọn ghi chú có sẵn', exact: true }).count(), 0);
    assert.equal(await eventEditor.getByRole('button', { name: 'Tạo ghi chú mới', exact: true }).count(), 0);
    await eventEditor.getByRole('button', { name: 'Đóng', exact: true }).click();
    const notes = () => api('notes');
    await page.getByTitle('Tạo ghi chú mới', { exact: true }).click();
    await noteEditor.getByPlaceholder('Tiêu đề ghi chú...').fill('Note lịch hẹn QA');
    await noteEditor.getByPlaceholder('Nhập nội dung ghi chú ở đây...').fill('Nội dung của ghi chú trên lịch');
    await noteEditor.getByRole('button', { name: 'Gắn vào lịch', exact: true }).click();
    assert.equal(await noteEditor.getByLabel('Ngày lịch hẹn', { exact: true }).inputValue(), display(today));
    await noteEditor.getByLabel('Giờ lịch hẹn', { exact: true }).fill('14:30');
    await noteEditor.getByPlaceholder('Tiêu đề ghi chú...').click();
    assert.equal(await noteEditor.getByLabel('Giờ kết thúc lịch hẹn', { exact: true }).inputValue(), '15:00');
    await page.screenshot({ path: 'tests/artifacts/note-scheduling-desktop.png', fullPage: true });
    const savedNote = page.waitForResponse(response => /\/api\/notes$/.test(response.url()) && response.request().method() === 'POST');
    await noteEditor.getByRole('button', { name: 'Lưu ghi chú', exact: true }).click();
    const note = await (await savedNote).json(); await noteEditor.waitFor({ state: 'hidden' });
    assert.ok(note.calendar_schedule.event_id); assert.equal(note.calendar_schedule.starts_at, `${today}T07:30:00Z`);
    const appointment = await api(`calendar/events/${note.calendar_schedule.event_id}`);
    assert.equal(appointment.note_count, undefined);
    assert.equal(await noteEditor.getByRole('button', { name: 'Gắn vào sự kiện', exact: true }).count(), 0);
    await calendar.locator(`[data-event-id="${appointment.id}"]`).waitFor();
    assert.equal(await calendar.locator(`[data-event-id="${appointment.id}"] .calendar-note-label`).count(), 0);
    await calendar.locator(`[data-event-id="${appointment.id}"]`).click(); await noteEditor.waitFor();
    await page.waitForFunction(() => document.querySelector('.note-editor-dialog textarea')?.value === 'Nội dung của ghi chú trên lịch');
    assert.equal(await page.getByRole('dialog', { name: 'Chi tiết sự kiện', exact: true }).count(), 0);
    assert.equal(await noteEditor.locator('.modal-content').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(254, 240, 138)');
    await noteEditor.getByPlaceholder('Tiêu đề ghi chú...').fill('Ghi chú lịch đã sửa');
    assert.equal(await noteEditor.getByLabel('Giờ lịch hẹn', { exact: true }).inputValue(), '14:30');
    await noteEditor.getByLabel('Giờ lịch hẹn', { exact: true }).fill('');
    await noteEditor.getByPlaceholder('Tiêu đề ghi chú...').click();
    assert.equal(await noteEditor.getByLabel('Giờ kết thúc lịch hẹn', { exact: true }).count(), 0);
    const updatedResponse = page.waitForResponse(response => response.url().includes(`/api/notes/${note.id}`) && response.request().method() === 'PATCH');
    await noteEditor.getByRole('button', { name: 'Lưu ghi chú', exact: true }).click();
    const updated = await (await updatedResponse).json(); await noteEditor.waitFor({ state: 'hidden' });
    assert.equal(updated.calendar_schedule.event_id, appointment.id); assert.equal(updated.calendar_schedule.is_all_day, true);
    const range = await api('calendar/events?start=' + encodeURIComponent(today + 'T00:00:00+07:00') + '&end=' + encodeURIComponent(today + 'T23:59:59+07:00'));
    assert.equal(range.filter(item => item.title === 'Ghi chú lịch đã sửa').length, 1);
    await page.getByRole('button', { name: 'Lịch', exact: true }).click();
    const calendarPage = page.locator('.calendar-page');
    for (const view of ['Tuần', 'Tháng', 'Danh sách']) {
      await calendarPage.getByRole('group', { name: 'Chế độ xem lịch', exact: true }).getByRole('button', { name: view, exact: true }).click();
      const item = calendarPage.locator(`button[data-event-id="${appointment.id}"]`).first(); await item.waitFor();
      assert.equal(await item.getByRole('img', { name: 'Ghi chú', exact: true }).count(), 1);
      await item.click(); await noteEditor.waitFor();
      await page.waitForFunction(() => document.querySelector('.note-editor-dialog input[placeholder="Tiêu đề ghi chú..."]')?.value === 'Ghi chú lịch đã sửa');
      assert.equal(await page.getByRole('dialog', { name: 'Chi tiết sự kiện', exact: true }).count(), 0);
      await noteEditor.getByRole('button', { name: 'Đóng ghi chú', exact: true }).click();
    }
    await calendarPage.getByRole('button', { name: 'Tạo sự kiện', exact: true }).click();
    await eventEditor.getByLabel('Tên sự kiện').fill('Sự kiện thường QA');
    const savedEvent = page.waitForResponse(response => /\/api\/calendar\/events$/.test(response.url()) && response.request().method() === 'POST');
    await eventEditor.getByRole('button', { name: 'Lưu sự kiện', exact: true }).click();
    const ordinary = await (await savedEvent).json(); await eventEditor.waitFor({ state: 'hidden' });
    await calendarPage.locator(`button[data-event-id="${ordinary.id}"]`).click();
    const ordinaryEditor = page.getByRole('dialog', { name: 'Chi tiết sự kiện', exact: true }); await ordinaryEditor.waitFor();
    assert.equal(await noteEditor.count(), 0); await ordinaryEditor.getByRole('button', { name: 'Đóng', exact: true }).click();
    await page.getByRole('button', { name: 'Workspace', exact: true }).click(); await calendar.waitFor();
    // Real PostgreSQL: simultaneous retries keep one note, one appointment and one event-note batch.
    const key = await page.evaluate(() => crypto.randomUUID());
    const schedule = { starts_at: today + 'T16:00:00+07:00', ends_at: today + 'T16:30:00+07:00', is_all_day: false };
    const sameNote = { title: 'Concurrent scheduled note QA', request_id: key, calendar_schedule: schedule };
    const noteRace = await Promise.all([api('notes', 'POST', sameNote), api('notes', 'POST', sameNote)]);
    assert.equal(noteRace[0].id, noteRace[1].id); assert.equal(noteRace[0].calendar_schedule.event_id, noteRace[1].calendar_schedule.event_id);
    await page.getByRole('button', { name: 'Chọn giao diện', exact: true }).click(); await page.getByRole('radio', { name: /Midnight Dark/ }).click(); await page.getByRole('button', { name: 'Đóng chọn giao diện', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByTitle('Tạo ghi chú mới', { exact: true }).click(); await noteEditor.getByRole('button', { name: 'Gắn vào lịch', exact: true }).click();
    await noteEditor.getByLabel('Ngày lịch hẹn', { exact: true }).click();
    const box = await noteEditor.locator('.app-date-popover').boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 391, JSON.stringify(box));
    await page.keyboard.press('Escape'); assert.ok(await noteEditor.isVisible());
    await noteEditor.getByRole('button', { name: 'Đóng ghi chú', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('PASS: removed event-link UI, retained scheduling/realtime, all-day conversion, concurrent replay, native note editor in widget/week/month/agenda, ordinary events unchanged, mobile dark mode');
  } finally { if (browser) await browser.close(); fixture.cleanup(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
