const { chromium } = require('../.browser-tools/node_modules/playwright');
const { createTestUsers } = require('../support/test-users.cjs');
const assert = require('node:assert/strict');

(async () => {
  const fixture = createTestUsers(1);
  let browser;
  try {
    browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'en-US', timezoneId: 'America/New_York' });
    page.setDefaultTimeout(20000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    let writes = 0;
    page.on('request', request => { if (/\/api\/calendar\/events(?:\/[^/?]+)?$/.test(request.url()) && ['POST', 'PUT'].includes(request.method())) writes++; });
    await page.goto('http://127.0.0.1:5173');
    await page.getByLabel('Tên đăng nhập hoặc Email').fill(fixture.accounts[0].username);
    await page.getByLabel('Mật khẩu', { exact: true }).fill(fixture.accounts[0].password);
    await page.getByRole('button', { name: 'Đăng nhập hệ thống' }).click();
    const widget = page.locator('.calendar-widget'); await widget.waitFor();
    const today = await page.evaluate(() => new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Ho_Chi_Minh' }));
    const display = date => date.split('-').reverse().join('/');
    await widget.getByRole('button', { name: 'Tạo sự kiện', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Tạo sự kiện mới', exact: true });
    const field = name => page.getByRole('dialog').getByRole('textbox', { name, exact: true });
    await field('Tên sự kiện').fill('Bộ chọn ngày giờ dùng chung');
    assert.equal(await field('Ngày bắt đầu').inputValue(), display(today));
    assert.equal(await dialog.locator('input[type=date], input[type=time]').count(), 0);
    await field('Ngày bắt đầu').click(); await dialog.locator('.app-date-popover').waitFor();
    await page.keyboard.press('Escape'); await dialog.locator('.app-date-popover').waitFor({ state: 'hidden' });
    assert.ok(await dialog.isVisible(), 'Escape closes the picker before the event dialog');
    await field('Ngày bắt đầu').fill('31/02/2026');
    assert.equal(await field('Ngày bắt đầu').evaluate(node => node.checkValidity()), false);
    await dialog.getByRole('button', { name: 'Lưu sự kiện', exact: true }).click(); assert.equal(writes, 0);
    await field('Ngày bắt đầu').fill('01/11/2026');
    assert.equal(await field('Ngày kết thúc').count(),0);
    assert.equal(await dialog.getByLabel('Lặp lại',{exact:true}).inputValue(),'NONE');
    await field('Ngày bắt đầu').fill(display(today));
    await field('Giờ bắt đầu').fill('24:00'); assert.equal(await field('Giờ bắt đầu').evaluate(node => node.checkValidity()), false);
    await field('Giờ bắt đầu').fill(''); assert.equal(await field('Giờ bắt đầu').evaluate(node => node.checkValidity()), false);
    await field('Giờ bắt đầu').fill('14:30'); await field('Giờ bắt đầu').click();
    const time = dialog.locator('.app-time-popover'); await time.waitFor();
    await time.getByRole('listbox', { name: 'Chọn giờ', exact: true }).selectOption('14');
    await time.getByRole('listbox', { name: 'Chọn phút', exact: true }).selectOption('30');
    await time.getByRole('button', { name: 'Xong', exact: true }).click();
    assert.equal(await field('Giờ bắt đầu').locator('..').locator('.app-time-period').innerText(), 'PM');
    await field('Giờ kết thúc').fill('13:30');
    await dialog.getByRole('button', { name: 'Lưu sự kiện', exact: true }).click();
    await dialog.getByRole('alert').filter({ hasText: 'Thời gian kết thúc phải sau' }).waitFor(); assert.equal(writes, 0);
    await field('Giờ kết thúc').fill('15:30');
    const save = async method => {
      const saved = page.waitForResponse(response => response.url().includes('/api/calendar/events') && response.request().method() === method);
      await page.getByRole('dialog').getByRole('button', { name: 'Lưu sự kiện', exact: true }).click();
      const response = await saved; assert.ok(response.ok()); const event = await response.json();
      await page.getByRole('dialog').waitFor({ state: 'hidden' }); return event;
    };
    const event = await save('POST');
    assert.equal(event.starts_at, `${today}T07:30:00Z`); assert.equal(event.ends_at, `${today}T08:30:00Z`);
    await widget.locator(`button[data-event-id="${event.id}"]`).click();
    await page.getByRole('dialog', { name: 'Chi tiết sự kiện', exact: true }).waitFor();
    assert.equal(await field('Giờ bắt đầu').inputValue(), '14:30');
    assert.ok(await page.getByRole('dialog').getByRole('checkbox',{name:'Sự kiện cả ngày',exact:true}).isDisabled());
    await page.getByRole('dialog').getByRole('button',{name:'Dời lịch / Thông báo',exact:true}).click();
    const mover=page.locator('.reschedule-dialog');await mover.getByRole('checkbox',{name:'Cả ngày',exact:true}).check();
    await mover.getByLabel('Ngày bắt đầu mới',{exact:true}).fill('01/11/2026');await mover.getByLabel('Ngày kết thúc mới',{exact:true}).fill('03/11/2026');
    const moved=page.waitForResponse(r=>r.url().includes('/api/schedule-changes/event/')&&r.request().method()==='POST');await mover.locator('button[type=submit]').click();assert.equal((await moved).status(),200);await mover.waitFor({state:'hidden'});
    assert.equal(await field('Ngày kết thúc').inputValue(),'03/11/2026');assert.ok(await field('Ngày kết thúc').isDisabled());
    await page.getByRole('dialog').getByRole('button',{name:'Đóng',exact:true}).click();
    const allDay=await page.request.get('http://127.0.0.1:5173/api/calendar/events/'+event.id,{headers:{Authorization:'Bearer '+await page.evaluate(()=>localStorage.getItem('dtl_platform_token'))}}).then(r=>r.json());
    assert.equal(allDay.is_all_day,true);assert.equal(allDay.starts_at,'2026-10-31T17:00:00Z');assert.equal(allDay.ends_at,'2026-11-03T17:00:00Z');
    await page.getByRole('button', { name: 'Chọn giao diện', exact: true }).click(); await page.getByRole('radio', { name: /Midnight Dark/ }).click(); await page.getByRole('button', { name: 'Đóng chọn giao diện', exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await widget.getByRole('button', { name: 'Tạo sự kiện', exact: true }).click();
    await field('Ngày bắt đầu').click();
    const popover = page.getByRole('dialog').locator('.app-date-popover'); await popover.waitFor();
    const box = await popover.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 391, JSON.stringify(box));
    await page.keyboard.press('Escape'); await popover.waitFor({ state: 'hidden' });
    await field('Giờ kết thúc').click();
    const timeBox = await page.getByRole('dialog').locator('.app-time-popover').boundingBox();
    assert.ok(timeBox.x >= 0 && timeBox.x + timeBox.width <= 391, JSON.stringify(timeBox));
    await page.screenshot({ path: 'tests/artifacts/event-date-time-mobile-dark.png', fullPage: true });
    await page.getByRole('dialog').getByRole('button', { name: 'Đóng', exact: true }).click();
    assert.deepEqual(errors, []);
    console.log('PASS: shared date/time pickers, dd/mm/yyyy, required/invalid fields, single-day end boundary, outside/Escape, 24-hour/PM, timed save/edit, all-day exclusive boundary, mobile and dark mode.');
  } finally { if (browser) await browser.close(); fixture.cleanup(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
